st.divider()  # 구분을 위한 구분선

# 라디오 버튼으로 사용자 선택 받기
place_choice = st.radio(
    "1. 어디서 활동하는 것을 선호하시나요?", ["실내", "야외"]
)

activity_choice = st.radio(
    "2. 어떤 유형의 먼작귀를 원하시나요?",
    ["정적인", "동적인"],
)

budget_choice = st.selectbox(
    "3. 생각하는 예산 수준을 선택해 주세요.",
    ["저예산", "중간 예산", "고예산"],
)

# ---------------------------------------------------------
# 4. 추천 로직 및 결과 출력
# ---------------------------------------------------------
st.divider()

